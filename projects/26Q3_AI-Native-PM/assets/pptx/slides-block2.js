// 헤딩(부분 문자열 일치) 다음 ~ 다음 헤딩 전까지의 ```text 코드 블록들을 순서대로 반환(generate-prompts-txt.py 와 같은 규칙)
function codeBlocksAfter(headingSub) {
  const start = LAB2.findIndex((l) => l.startsWith("#") && l.includes(headingSub));
  if (start < 0) throw new Error(`lab-2 heading not found: ${headingSub}`);
  let end = LAB2.length, fence = false;
  for (let i = start + 1; i < LAB2.length; i++) {
    if (LAB2[i].startsWith("```")) { fence = !fence; continue; }
    if (!fence && LAB2[i].startsWith("#")) { end = i; break; }
  }
  const out = []; let cur = [], inb = false;
  for (const l of LAB2.slice(start, end)) {
    if (l.startsWith("```")) { if (inb) { out.push(cur.join("\n").replace(/\s+$/, "")); cur = []; inb = false; } else inb = true; continue; }
    if (inb) cur.push(l);
  }
  return out;
}
// 줄 단위로 markers(각 파트가 시작하는 줄의 접두어) 위치에서 잘라 N개 파트로
function splitAt(text, markers) {
  const lines = text.split("\n");
  const cuts = markers.map((m) => lines.findIndex((l) => l.trim().startsWith(m))).filter((i) => i > 0).sort((a, b) => a - b);
  const parts = []; let prev = 0;
  for (const c of cuts) { parts.push(lines.slice(prev, c).join("\n").replace(/\s+$/, "")); prev = c; }
  parts.push(lines.slice(prev).join("\n").replace(/\s+$/, ""));
  return parts;
}

