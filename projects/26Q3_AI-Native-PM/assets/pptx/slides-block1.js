// ── 프롬프트 전문 로더(요약·수정 금지 — 헤더 줄만 제거하고 (1/2)(2/2) 분할) ──
function readPromptTxt(file) {
  const raw = fs.readFileSync(path.join(PT, file), "utf8").replace(/\r\n/g, "\n");
  const lines = raw.split("\n");
  if (lines[0].startsWith("※")) lines.shift();
  while (lines.length && lines[0].trim() === "") lines.shift();
  while (lines.length && lines[lines.length - 1].trim() === "") lines.pop();
  return lines;
}
function splitAt(lines, pred) {
  const i = lines.findIndex(pred);
  if (i < 0) throw new Error("split marker not found");
  return [lines.slice(0, i).join("\n"), lines.slice(i).join("\n")];
}
// lab-1 §1.2 빈 카드 — MD 코드 블록에서 그대로 추출(prompts-txt에 아직 .txt 없음)
function readBlankCard() {
  const md = fs.readFileSync(path.join(WS, "lab-1-prompt-design.md"), "utf8").replace(/\r\n/g, "\n").split("\n");
  const h = md.findIndex((l) => l.startsWith("###") && l.includes("1.2 템플릿 카드"));
  if (h < 0) throw new Error("lab-1 §1.2 heading not found");
  const s = md.findIndex((l, i) => i > h && l.startsWith("```"));
  const e = md.findIndex((l, i) => i > s && l.startsWith("```"));
  return md.slice(s + 1, e).join("\n");
}

