// ── 프롬프트 .txt 읽기: 상단 "※ …" 안내 줄과 빈 줄만 걷어낸다(본문은 그대로) · 파일이 없으면 lab-3 코드 블록 복사본(fallback) ──
function readPrompt(file, fallback) {
  const p = path.join(PT, file);
  if (!fs.existsSync(p)) return fallback;
  const lines = fs.readFileSync(p, "utf8").split("\n");
  while (lines.length && (/^※/.test(lines[0]) || lines[0].trim() === "")) lines.shift();
  return lines.join("\n").trim();
}

// ── 회의 메모 본문(sample-data) — 날짜 줄부터 끝까지 ──
function memoBody() {
  const p = path.join(WS, "sample-data", "moneyfit-kickoff-meeting-notes.md");
  if (!fs.existsSync(p)) return MEMO_FALLBACK;
  const lines = fs.readFileSync(p, "utf8").split("\n");
  const i = lines.findIndex((l) => /^\d{1,2}\/\d{1,2}\(/.test(l));
  return (i >= 0 ? lines.slice(i) : lines).join("\n").trim();
}

