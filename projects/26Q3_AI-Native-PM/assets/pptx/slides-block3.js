    const innerH = (4.70 - 1.5) - 0.36 - (o.kicker ? 0.3 : 0) - (o.note ? 0.5 : 0) - 0.22;
    const fits = (chunk, size) => {
      const counts = chunk.map((p) => deck.estimateLines(p, colW, size));
      const total = counts.reduce((a, b) => a + b, 0);
      let acc = 0, cut = chunk.length;
      for (let i = 0; i < chunk.length; i++) { acc += counts[i]; if (acc >= total / 2) { cut = i + 1; break; } }
      const left = counts.slice(0, cut).reduce((a, b) => a + b, 0), right = total - left;
      const maxLines = Math.floor(innerH / ((size / 72) * 1.38));
      return left <= maxLines && right <= maxLines;
    };
    const pages = []; let cur = [];
    for (const p of paras) {
      const next = cur.concat([p]);
      if (cur.length === 0 || fits(next, target)) cur = next; else { pages.push(cur); cur = [p]; }
    }
    if (cur.length) pages.push(cur);
